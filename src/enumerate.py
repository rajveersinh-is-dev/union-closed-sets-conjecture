"""
Exact enumeration of union-closed families on small ground sets.

A union-closed family is determined by its inclusion-minimal non-empty
member-sets (an antichain): the family consists of the empty set together
with all unions of subfamilies of the antichain.  This gives a one-to-one
correspondence between antichains of non-empty subsets of [n] and
union-closed families containing the empty set.

Families NOT containing the empty set are the "easier" case: removing the
empty set only raises every element's frequency fraction d(x)/m, so it
suffices to verify families containing the empty set.  Hence enumerating
antichains verifies Frankl's conjecture for all union-closed families on
<= n ground elements (computationally, for small n).

Usage:
    python src/enumerate.py        # n = 5 (full enumeration)
    python src/enumerate.py 6      # n = 6 (~7.8M antichains, slow)

All arithmetic is exact integer arithmetic.  This is computation as an
assistant: it verifies finite cases and builds intuition; it proves nothing
for general n.
"""

from __future__ import annotations

from time import time
import functools
import sys



def antichains(n: int):
    """Generate all antichains of non-empty subsets of [n].

    Subsets are represented as bitmasks in {1, ..., 2^n - 1}.
    Yields tuples of bitmasks, each an inclusion-antichain.
    Memory-efficient: yields one antichain at a time instead of storing all.
    """
    subsets = list(range(1, 1 << n))

    @functools.lru_cache(maxsize=None)
    def rec(i: int, chosen: list[int]):
        """Rec.
        
        Args:
            i:
            chosen:
        
        """
        if i == len(subsets):
            yield tuple(chosen)
            return
        s = subsets[i]
        # Option 1: exclude s.
        yield from rec(i + 1, chosen)
        # Option 2: include s, only if incomparable with every chosen set.
        ok = True
        for c in chosen:
            inter = s & c
            if inter == s or inter == c:  # s subseteq c or c subseteq s
                ok = False
                break
        if ok:
            yield from rec(i + 1, chosen + [s])

    yield from rec(0, [])


def union_closure(antichain: tuple[int, ...], n: int) -> list[int]:
    """Return the union-closed family (as list of bitmasks, incl. empty)
    generated by an antichain of minimal sets."""
    full = (1 << n) - 1
    family = {0}  # always include the empty set (the harder case)
    k = len(antichain)
    # All unions of subfamilies of the antichain.
    for mask in range(1, 1 << k):
        u = 0
        mm = mask
        idx = 0
        while mm:
            if mm & 1:
                u |= antichain[idx]
            mm >>= 1
            idx += 1
        family.add(u)
    return sorted(family)


def frequencies(family: list[int], n: int) -> list[int]:
    """d(x) for each element x in [n] (element x <-> bit x)."""
    d = [0] * n
    for A in family:
        bits = A
        x = 0
        while bits:
            if bits & 1:
                d[x] += 1
            bits >>= 1
            x += 1
    return d


def main() -> None:
    """Entry point — parse arguments and run the main computation.
    
    """
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    if n < 1 or n > 6:
        print("Use n in 1..6 (n=6 is ~7.8M antichains and slow).")
        return

    t0 = time()
    total_families = 0
    verified = 0
    counterexample_count = 0
    first_counterexample = None
    # Track extremal: minimize max frequency fraction.
    best_ratio = 1.0
    best_example = None

    for antichain in antichains(n):
        if not antichain:
            # family = {empty}, the excluded trivial case; skip.
            continue
        family = union_closure(antichain, n)
        m = len(family)
        total_families += 1
        d = frequencies(family, n)
        maxd = max(d) if n >= 1 else 0
        # Frankl: exists x with d(x) >= m/2  <=>  2*maxd >= m
        if 2 * maxd >= m:
            verified += 1
        else:
            counterexample_count += 1
            if first_counterexample is None:
                first_counterexample = (antichain, family, d)
        ratio = maxd / m
        if ratio < best_ratio - 1e-12:
            best_ratio = ratio
            best_example = (antichain, family, d, m)

    dt = time() - t0
    print(f"Ground set size: n = {n}")
    print(f"Union-closed families enumerated: {total_families}")
    print(f"Satisfying Frankl (max d(x) >= m/2): {verified}")
    print(f"Counterexamples found: {counterexample_count}")
    print(f"Elapsed: {dt:.2f}s")
    print(f"Best (smallest) max-frequency ratio: {best_ratio:.6f}")
    if first_counterexample:
        ant, fam, d = first_counterexample
        print("FIRST COUNTEREXAMPLE:")
        print("  minimal sets:", [format(a, f'0{n}b') for a in ant])
        print("  family size m:", len(fam), "frequencies d(x):", d)
    else:
        print("CONJECTURE VERIFIED for all union-closed families on [n].")

    if best_example:
        ant, fam, d, m = best_example
        print("\nExtremal family (minimal sets):")
        print("  ", [format(a, f'0{n}b') for a in ant])
        print("  family:", [format(a, f'0{n}b') for a in fam])
        print("  m =", len(fam), "d(x) =", d, "max/m =", max(d) / len(fam))


if __name__ == "__main__":
    main()
